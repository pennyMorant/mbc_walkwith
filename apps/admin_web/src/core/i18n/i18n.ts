export function useI18n() {
  const localeOptions = computed(() =>
    supportedLocales.map((locale) => ({
      ...locale,
      title: messages[currentLocale.value][`locale.${locale.value}`] ?? locale.title
    }))
  );

  function t(key: string): string {
    return messages[currentLocale.value][key] ?? messages.en[key] ?? key;
  }

  function setLocale(locale: AppLocale) {
    currentLocale.value = locale;
    localStorage.setItem(storageKey, locale);
  }

  function resetLocaleToSystem() {
    localStorage.removeItem(storageKey);
    currentLocale.value = readSystemLocale();
  }

  function optionTitle(value: string) {
    return value ? t(value) : t("common.all");
  }

  function optionItems<T extends string>(values: readonly T[]) {
    return values.map((value) => ({
      title: optionTitle(value),
      value
    }));
  }

  return {
    locale: currentLocale,
    localeOptions,
    optionItems,
    optionTitle,
    resetLocaleToSystem,
    setLocale,
    t
  };
}

function readLocale(): AppLocale {
  const stored = localStorage.getItem(storageKey);
  const storedLocale = normalizeLocale(stored);
  if (storedLocale) {
    return storedLocale;
  }
  return readSystemLocale();
}

function readSystemLocale(): AppLocale {
  for (const language of navigator.languages ?? [navigator.language]) {
    const locale = normalizeLocale(language);
    if (locale) {
      return locale;
    }
  }

  return "zh-Hans";
}

function normalizeLocale(value: string | null | undefined): AppLocale | null {
  if (!value) {
    return null;
  }
  const normalized = value.replace("_", "-").toLowerCase();
  if (
    normalized === "zh-hant" ||
    normalized.startsWith("zh-tw") ||
    normalized.startsWith("zh-hk")
  ) {
    return "zh-Hant";
  }
  if (
    normalized === "zh-hans" ||
    normalized.startsWith("zh-cn") ||
    normalized.startsWith("zh-sg") ||
    normalized === "zh"
  ) {
    return "zh-Hans";
  }
  if (normalized.startsWith("es")) {
    return "es";
  }
  if (normalized.startsWith("en")) {
    return "en";
  }
  return null;
}
