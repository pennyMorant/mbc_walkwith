import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const args = new Set(process.argv.slice(2));
const strict = args.has("--strict");
const envArg = process.argv.find((arg) => arg.startsWith("--env="));
const envPath = envArg ? envArg.slice("--env=".length) : undefined;
const env = {
  ...process.env,
  ...(envPath ? parseEnvFile(envPath) : {})
};

const checks = [];

function parseEnvFile(relativePath) {
  const fullPath = path.isAbsolute(relativePath)
    ? relativePath
    : path.join(root, relativePath);
  const content = readFileSync(fullPath, "utf8");
  const parsed = {};

  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }
    const separator = line.indexOf("=");
    if (separator <= 0) {
      continue;
    }
    const key = line.slice(0, separator).trim();
    const value = line.slice(separator + 1).trim().replace(/^["']|["']$/g, "");
    parsed[key] = value;
  }

  return parsed;
}

function requireValue(key, label = key) {
  const value = env[key]?.trim();
  const usable = isUsableValue(value);
  addCheck({
    label,
    status: usable ? "ready" : "missing",
    detail: usable
      ? `${key} is set.`
      : `${key} is required and must not be a placeholder value.`
  });
  return usable;
}

function addCheck(check) {
  checks.push(check);
}

function isUsableValue(value) {
  const trimmed = value?.trim();
  if (!trimmed) {
    return false;
  }
  return !/(<[^>]+>|replace-|change-me|example\.com|password123|dev-only)/i.test(
    trimmed
  );
}

function firebaseOptionsConfigured() {
  const firebaseOptionsPath = path.join(
    root,
    "apps/mobile/lib/firebase_options.dart"
  );
  if (!existsSync(firebaseOptionsPath)) {
    return false;
  }
  const source = readFileSync(firebaseOptionsPath, "utf8");
  return !source.includes("Placeholder Firebase options file");
}

function backendReadiness() {
  const useMockData = env.USE_MOCK_DATA === "true" || env.USE_MOCK_DATA === "1";

  addCheck({
    label: "Postgres mode",
    status: isUsableValue(env.DATABASE_URL) && !useMockData ? "ready" : "missing",
    detail: env.DATABASE_URL
      ? useMockData
        ? "DATABASE_URL is set but USE_MOCK_DATA is enabled."
        : isUsableValue(env.DATABASE_URL)
          ? "DATABASE_URL is set and USE_MOCK_DATA is not enabled."
          : "DATABASE_URL is a placeholder value."
      : "DATABASE_URL is required for staging or production testing."
  });

  const authReady =
    isUsableValue(env.auth_secret) && isUsableValue(env.app_user_auth_secret);
  addCheck({
    label: "Backend auth secrets",
    status: authReady ? "ready" : "missing",
    detail:
      "auth_secret and app_user_auth_secret must be unique non-development secrets."
  });

  addCheck({
    label: "Debug member bypass",
    status:
      env.NODE_ENV === "production" || env.DEBUG_MEMBER_AUTH_BYPASS === "false"
        ? "ready"
        : "warning",
    detail:
      "Disable DEBUG_MEMBER_AUTH_BYPASS outside local developer testing."
  });
}

function storageReadiness() {
  const driver = env.MEDIA_STORAGE_DRIVER || "local";
  if (driver === "s3") {
    const ready = ["S3_BUCKET", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY"].every(
      (key) => isUsableValue(env[key])
    );
    addCheck({
      label: "Object storage",
      status: ready ? "ready" : "missing",
      detail: ready
        ? "S3/R2 media storage is configured."
        : "S3_BUCKET, S3_ACCESS_KEY_ID, and S3_SECRET_ACCESS_KEY are required when MEDIA_STORAGE_DRIVER=s3."
    });
    return;
  }

  addCheck({
    label: "Object storage",
    status: "warning",
    detail:
      "MEDIA_STORAGE_DRIVER=local is acceptable for a small VPS test, but R2/S3 should be used before production."
  });
}

function stripeReadiness() {
  const secretReady = requireValue("STRIPE_SECRET_KEY", "Stripe secret key");
  const webhookReady = requireValue(
    "STRIPE_WEBHOOK_SECRET",
    "Stripe webhook secret"
  );
  addCheck({
    label: "Stripe checkout URLs",
    status:
      isUsableValue(env.GIVING_CHECKOUT_SUCCESS_URL) &&
      isUsableValue(env.GIVING_CHECKOUT_CANCEL_URL)
        ? "ready"
        : "warning",
    detail:
      "Set GIVING_CHECKOUT_SUCCESS_URL and GIVING_CHECKOUT_CANCEL_URL for the target App or web return path."
  });
  return secretReady && webhookReady;
}

function notificationReadiness() {
  addCheck({
    label: "Mobile Firebase options",
    status: firebaseOptionsConfigured() ? "ready" : "missing",
    detail:
      "apps/mobile/lib/firebase_options.dart must be generated by flutterfire configure for real push testing."
  });

  addCheck({
    label: "Backend FCM service account",
    status: isUsableValue(env.FCM_SERVICE_ACCOUNT_JSON) ? "ready" : "missing",
    detail:
      "FCM_SERVICE_ACCOUNT_JSON is required for backend push delivery through FCM HTTP v1."
  });
}

function aiReadiness() {
  const provider = env.AI_PROVIDER || "disabled";
  if (provider === "disabled") {
    addCheck({
      label: "AI provider",
      status: "warning",
      detail:
        "AI_PROVIDER=disabled. This is safe, but AI Bible study and admin drafting cannot be fully tested."
    });
    return;
  }

  const ready =
    isUsableValue(env.AI_API_KEY) &&
    isUsableValue(env.AI_MODEL) &&
    (provider !== "openai_compatible" || isUsableValue(env.AI_BASE_URL));
  addCheck({
    label: "AI provider",
    status: ready ? "ready" : "missing",
    detail:
      provider === "openai_compatible"
        ? "AI_API_KEY, AI_MODEL, and AI_BASE_URL are required for compatible providers."
        : "AI_API_KEY and AI_MODEL are required."
  });
}

backendReadiness();
storageReadiness();
stripeReadiness();
notificationReadiness();
aiReadiness();

const missing = checks.filter((check) => check.status === "missing");
const warnings = checks.filter((check) => check.status === "warning");

for (const check of checks) {
  const marker = check.status === "ready"
    ? "ok"
    : check.status === "warning"
      ? "warn"
      : "missing";
  console.log(`[${marker}] ${check.label}: ${check.detail}`);
}

console.log(
  `Release readiness summary: ${checks.length - missing.length - warnings.length} ready, ${warnings.length} warning, ${missing.length} missing.`
);

if (strict && missing.length > 0) {
  process.exit(1);
}
